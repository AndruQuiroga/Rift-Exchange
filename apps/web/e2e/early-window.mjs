import {chromium, expect} from '@playwright/test';
import {mkdirSync} from 'node:fs';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:390,height:844}});
page.on('pageerror', e=>console.error('PAGE ERROR',e.message));
const team=(id,code)=>({id,code,name:code,image_url:null,region:null});
const event={id:'ui-window',stage:'Swiss',best_of:1,scheduled_at:new Date().toISOString(),local_date:'2026-10-20',status:'LIVE',team_a:team('a','GEN'),team_b:team('b','T1'),score:[0,0],winner:null,markets:[{id:'winner',kind:'series_winner',scope:'SERIES',category:'WINNER',title:'Match winner',state:'LOCKED',rules:'',params:{},close_at:new Date().toISOString(),outcomes:[{id:'a',code:'A',label:'GEN',odds:'2.00'},{id:'b',code:'B',label:'T1',odds:'2.00'}]}],games:[{index:1,state:'inProgress',started_at:new Date().toISOString(),ended_at:null,winner:null,window:'LOCKED',opens_when:null,closes_at:null,burned_champions:[]}]};
let state='UPCOMING';
const window=()=>({open:state==='OPEN',state,close_at:state==='OPEN'?new Date(Date.now()+65000).toISOString():null,opens_when:'When the game loads'});
await page.route('**/api/v1/**',async route=>{
 const p=new URL(route.request().url()).pathname;
 let body={};
 if(p.endsWith('/me')) body={user:{id:'u',display_name:'Tester'},wallet:{available_rc:1000},grant_today:null};
 else if(p.endsWith('/season/current')) body={match_days:[],timezone:'America/Chicago'};
 else if(p.endsWith('/duels')) body={...window(),stats:[{id:'kills',label:'More kills'}],duels:[{role:'mid',a:{player_id:'1',name:'Chovy',champion:state==='UPCOMING'?null:'Ahri'},b:{player_id:'2',name:'Faker',champion:state==='UPCOMING'?null:'Azir'},odds:{kills:{A:'2.00',B:'2.00'}}}]};
 else if(p.endsWith('/kill-lines')) body={...window(),typical:'27.5',lines:state==='OPEN'?[{line:'27.5',over:'2.00',under:'2.00'}]:[]};
 else if(p.endsWith('/draft')) body={game_index:1,open:false,close_at:null,games_observed:0,scopes:[],burned:[],champions:[]};
 else if(p.endsWith('/live')) body={status:'SCHEDULED'};
 else if(p.endsWith('/ui-window')) body=event;
 else if(p.endsWith('/stream')) return route.fulfill({status:200,contentType:'text/event-stream',body:''});
 await route.fulfill({json:body});
});
await page.goto('http://localhost:3010/events/ui-window');

await page.locator('details.builder').filter({has:page.locator('summary .t',{hasText:'Players'})}).locator('summary').click();
await expect(page.getByText('Opens after draft, when champions are confirmed.').first()).toBeVisible();
await expect(page.getByRole('button',{name:/Chovy,/})).toBeDisabled();
state='OPEN';
await expect(page.getByText('Ahri',{exact:true})).toBeVisible({timeout:10000});
await expect(page.getByRole('button',{name:/Chovy,/})).toBeEnabled();
await page.locator('details.builder').filter({has:page.locator('summary .t',{hasText:'Game',exact:true})}).locator('summary').click();
await expect(page.getByRole('slider',{name:'Kill line'})).toBeVisible();
mkdirSync('../../artifacts/p4-ui',{recursive:true});
await page.screenshot({path:'../../artifacts/p4-ui/early-open.png',fullPage:true});
state='CLOSED';
await expect(page.getByRole('button',{name:/Chovy,/})).toBeDisabled({timeout:10000});
await expect(page.getByText('Early-game picks closed.').first()).toBeVisible();
if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)) throw Error('horizontal overflow');
console.log('PASS: upcoming/open/closed, champions, slider and phone width');
await browser.close();
